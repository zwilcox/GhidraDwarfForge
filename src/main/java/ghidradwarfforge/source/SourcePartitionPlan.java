package ghidradwarfforge.source;

import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;
import java.util.Objects;
import java.util.concurrent.CancellationException;
import java.util.function.BooleanSupplier;

/**
 * Partitions an already composed source without changing its logical line or
 * address evidence. File zero is reserved for the eventual synthetic index;
 * actual source parts use file numbers one and above.
 */
public final class SourcePartitionPlan {
    private static final byte[] HEADER = ("/* Synthetic source partition generated by GhidraDwarfForge. */\n" +
        "/* Decompiled presentation, not recovered original source. */\n").getBytes(StandardCharsets.UTF_8);
    private static final int HEADER_LINES = 2;

    public record Position(int file, int line) {
        public Position {
            if (file < 1 || line < 1) throw new IllegalArgumentException("invalid partition position");
        }
    }

    public static final class Part {
        private final int file;
        private final int firstLogicalLine;
        private final int lastLogicalLine;
        private final boolean oversized;
        private final byte[] utf8;

        private Part(int file, int first, int last, int limit, byte[] utf8) {
            this.file = file;
            this.firstLogicalLine = first;
            this.lastLogicalLine = last;
            this.oversized = last - first + 1 > limit;
            this.utf8 = utf8;
        }

        public int file() { return file; }
        public int firstLogicalLine() { return firstLogicalLine; }
        public int lastLogicalLine() { return lastLogicalLine; }
        public boolean oversized() { return oversized; }
        public byte[] utf8() { return utf8.clone(); }
    }

    private final List<Part> parts;
    private final int logicalLineCount;
    private final String sourceSha256;

    private SourcePartitionPlan(List<Part> parts, int logicalLineCount, byte[] source) {
        this.parts = List.copyOf(parts);
        this.logicalLineCount = logicalLineCount;
        this.sourceSha256 = digest(source);
    }

    public List<Part> parts() { return parts; }
    public int logicalLineCount() { return logicalLineCount; }
    public String sourceSha256() { return sourceSha256; }

    public static byte[] syntheticHeader() { return HEADER.clone(); }

    public void requireSource(SyntheticSourceFile source) {
        if (source == null || !sourceSha256.equals(digest(source.utf8()))) {
            throw new IllegalArgumentException("partition plan does not describe the supplied source");
        }
    }

    /**
     * The line target excludes the fixed synthetic header. Whole functions and
     * the preamble remain indivisible, even when one exceeds the target.
     */
    public static SourcePartitionPlan build(SyntheticSourceFile source, int targetLines,
            BooleanSupplier cancelled) {
        Objects.requireNonNull(source, "source");
        Objects.requireNonNull(cancelled, "cancelled");
        if (targetLines < 1) throw new IllegalArgumentException("source line target must be positive");
        check(cancelled);
        byte[] bytes = source.utf8();
        if (bytes.length == 0 || bytes[bytes.length - 1] != '\n') {
            throw new IllegalArgumentException("partitioned source must end in LF");
        }
        int count = 0;
        for (int index = 0; index < bytes.length; index++) {
            if ((index & 4095) == 0) check(cancelled);
            if (bytes[index] == '\n') count++;
        }
        int[] offsets = new int[Math.addExact(count, 1)];
        int line = 1;
        for (int index = 0; index < bytes.length; index++) {
            if ((index & 4095) == 0) check(cancelled);
            if (bytes[index] == '\n') offsets[line++] = index + 1;
        }
        List<Integer> boundaries = new ArrayList<>(List.of(1));
        int previousEnd = 0;
        for (var function : source.functions()) {
            check(cancelled);
            if (function.startLine() <= previousEnd || function.endLine() < function.startLine() ||
                    function.endLine() > count) {
                throw new IllegalArgumentException("overlapping, unordered or invalid source function boundaries");
            }
            if (function.startLine() > 1) boundaries.add(function.startLine());
            previousEnd = function.endLine();
        }
        boundaries.add(Math.addExact(count, 1));
        for (var row : source.mappedLines()) {
            check(cancelled);
            requireLine(row.line(), count);
        }
        for (var function : source.functionTokens()) {
            check(cancelled);
            for (var row : function.lines()) {
                check(cancelled);
                requireLine(row.line(), count);
            }
        }
        List<Part> parts = new ArrayList<>();
        int first = 1;
        int last = 0;
        for (int index = 0; index + 1 < boundaries.size(); index++) {
            check(cancelled);
            int unitFirst = boundaries.get(index);
            int unitLast = boundaries.get(index + 1) - 1;
            if (last >= first && (long) unitLast - first + 1 > targetLines) {
                parts.add(part(parts.size() + 1, first, last, targetLines, bytes, offsets));
                first = unitFirst;
            }
            last = unitLast;
        }
        parts.add(part(parts.size() + 1, first, last, targetLines, bytes, offsets));
        check(cancelled);
        return new SourcePartitionPlan(parts, count, bytes);
    }

    /** Translate a logical line only; no addresses or function/type identities change. */
    public Position locate(int logicalLine) {
        requireLine(logicalLine, logicalLineCount);
        int low = 0;
        int high = parts.size() - 1;
        while (low <= high) {
            int middle = low + (high - low) / 2;
            Part part = parts.get(middle);
            if (logicalLine < part.firstLogicalLine()) high = middle - 1;
            else if (logicalLine > part.lastLogicalLine()) low = middle + 1;
            else return new Position(part.file(), logicalLine - part.firstLogicalLine() + 1 + HEADER_LINES);
        }
        throw new IllegalStateException("source partition has an uncovered logical line");
    }

    private static Part part(int file, int first, int last, int limit, byte[] bytes, int[] offsets) {
        ByteArrayOutputStream output = new ByteArrayOutputStream();
        output.writeBytes(HEADER);
        output.writeBytes(Arrays.copyOfRange(bytes, offsets[first - 1], offsets[last]));
        return new Part(file, first, last, limit, output.toByteArray());
    }

    private static void requireLine(int line, int count) {
        if (line < 1 || line > count) throw new IllegalArgumentException("source line is outside partition input");
    }

    private static String digest(byte[] bytes) {
        try {
            return java.util.HexFormat.of().formatHex(java.security.MessageDigest.getInstance("SHA-256").digest(bytes));
        }
        catch (java.security.NoSuchAlgorithmException impossible) {
            throw new IllegalStateException("Java runtime lacks SHA-256", impossible);
        }
    }

    private static void check(BooleanSupplier cancelled) {
        if (cancelled.getAsBoolean()) throw new CancellationException("source partitioning cancelled");
    }
}
