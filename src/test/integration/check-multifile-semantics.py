#!/usr/bin/env python3
"""Compare production single/multi-file DWARF without merging DIEs by name.

LLVM independently decodes attributes and line rows. Only source coordinates,
CU presentation paths and DIE reference offsets are normalized. Range/location
tables and other non-presentation DWARF sections must remain byte-identical.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess


def require(condition, message):
    if not condition:
        raise ValueError(message)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def command(*args):
    result = subprocess.run(args, capture_output=True, text=True, timeout=120)
    require(result.returncode == 0 and not result.stderr, repr(args) + result.stderr)
    require(not re.search(r'\b(?:warning|error):', result.stdout, re.I), result.stdout)
    return result.stdout


def bundle(source, original, baseline):
    names = re.findall(r'^ \* Manifest: (forge-src-[0-9a-f]{64}\.json)$',
        source.read_text(), re.M)
    require(len(names) == 1, 'missing/ambiguous source manifest')
    manifest_path = source.parent / names[0]
    raw = manifest_path.read_bytes()
    require(names[0] == 'forge-src-' + digest(raw) + '.json', 'manifest hash mismatch')
    manifest = json.loads(raw)
    require(manifest['schema'] == 1 and manifest['indexName'] == source.name,
        'incorrect bundle identity')
    require(manifest['inputSha256'] == digest(original.read_bytes()), 'wrong original input')
    logical = bytearray()
    cursor = 1
    for index, part in enumerate(manifest['parts'], 1):
        require(part['file'] == index and part['first'] == cursor and part['last'] >= cursor,
            'invalid source partition bounds')
        require(part['name'] == 'forge-src-%06d-%s.c' % (index, part['sha256']), 'invalid part name')
        data = (source.parent / part['name']).read_bytes()
        require(len(data) == part['bytes'] and digest(data) == part['sha256'], 'invalid part content')
        lines = data.splitlines(keepends=True)
        require(lines[:2] == [b'/* Synthetic source partition generated by GhidraDwarfForge. */\n',
            b'/* Decompiled presentation, not recovered original source. */\n'], 'missing synthetic labels')
        require(len(lines) == part['last'] - part['first'] + 3, 'part line count changed')
        logical.extend(b''.join(lines[2:]))
        cursor = part['last'] + 1
    require(len(manifest['parts']) > 1, 'fixture did not exercise multiple source files')
    require(digest(logical) == manifest['logicalSourceSha256'], 'logical source hash mismatch')
    require(logical == baseline.read_bytes(), 'partitioning changed the logical source')
    return manifest


def number(value):
    require(re.fullmatch(r'\((?:0x[0-9a-f]+|[0-9]+)\)', value), 'undecoded number: ' + value)
    text = value[1:-1]
    return int(text, 16 if text.startswith('0x') else 10)


def path_value(value):
    require(value.startswith('("') and value.endswith('")'), 'undecoded path: ' + value)
    return json.loads(value[1:-1])


def logical_line(part, line):
    require(3 <= line <= part['last'] - part['first'] + 3, 'coordinate refers to header/outside part')
    return part['first'] + line - 3


def dies(text, source, manifest=None):
    units = re.findall(r'^0x[0-9a-f]+: Compile Unit:.*$', text, re.M)
    require(len(units) == 1 and 'version = 0x0005' in units[0], 'expected one DWARF 5 CU')
    headers = list(re.finditer(r'^0x([0-9a-f]+):( +)(DW_TAG_\w+|NULL)\s*$', text, re.M))
    require(headers and headers[0][3] == 'DW_TAG_compile_unit', 'missing CU DIE')
    offsets = {int(header[1], 16): i for i, header in enumerate(headers)}
    require(len(offsets) == len(headers), 'duplicate DIE offsets')
    result = []
    parts = {str(source.parent / part['name']): part for part in manifest['parts']} if manifest else {}
    for i, header in enumerate(headers):
        body = text[header.end():headers[i + 1].start() if i + 1 < len(headers) else len(text)]
        attributes = list(re.finditer(r'^\s+(DW_AT_\w+) \[(DW_FORM_\w+)\]\s+', body, re.M))
        values = {}
        for j, attr in enumerate(attributes):
            value = ' '.join(body[attr.end():attributes[j + 1].start() if j + 1 < len(attributes) else len(body)].split())
            name, form = attr[1], attr[2]
            require(name not in values, 'duplicate attribute ' + name)
            if form.startswith('DW_FORM_ref'):
                match = re.match(r'\((0x[0-9a-f]+)(.*)', value)
                require(match is not None and int(match[1], 16) in offsets, 'unresolved DIE reference')
                value = '(DIE#%d%s' % (offsets[int(match[1], 16)], match[2])
            values[name] = [form, value]
        require(attributes or not body.strip(), 'unparsed DIE body')
        if header[3] == 'DW_TAG_compile_unit':
            require(path_value(values['DW_AT_name'][1]) == source.name, 'CU source name mismatch')
            require(path_value(values['DW_AT_comp_dir'][1]) == str(source.parent), 'CU directory mismatch')
            values['DW_AT_name'][1] = '<synthetic-source>'
            values['DW_AT_comp_dir'][1] = '<source-directory>'
        if 'DW_AT_decl_file' in values:
            path = path_value(values['DW_AT_decl_file'][1])
            require('DW_AT_decl_line' in values, 'declaration file without line')
            line = number(values['DW_AT_decl_line'][1])
            if manifest:
                require(path in parts, 'declaration refers outside source bundle')
                line = logical_line(parts[path], line)
            else:
                require(path == str(source), 'declaration refers outside baseline source')
                require(1 <= line <= len(source.read_bytes().splitlines()), 'baseline declaration out of bounds')
            values['DW_AT_decl_file'] = ['coordinate', '<logical-source>']
            values['DW_AT_decl_line'] = ['coordinate', line]
        result.append({'depth': len(header[2]), 'tag': header[3], 'attributes': values})
    return result


def line_rows(text, source, manifest=None):
    files = re.findall(r'file_names\[\s*(\d+)\]:\s*\n\s*name: (".*")\s*\n\s*dir_index: (\d+)', text)
    expected = [source.name] + ([part['name'] for part in manifest['parts']] if manifest else [])
    require([(int(i), json.loads(name), int(directory)) for i, name, directory in files] ==
        [(i, name, 0) for i, name in enumerate(expected)], 'line file table differs from complete inventory')
    directories = re.findall(r'include_directories\[\s*(\d+)\] = (".*")', text)
    require([(int(i), json.loads(path)) for i, path in directories] == [(0, str(source.parent))],
        'line directory mismatch')
    rows = []
    for line in text.splitlines():
        if not line.startswith('0x'):
            continue
        fields = line.split()
        require(len(fields) >= 7, 'malformed line row')
        address, local, column, file, isa, discriminator, op = [int(fields[0], 16), *map(int, fields[1:7])]
        if manifest:
            require(1 <= file <= len(manifest['parts']), 'executable row refers outside parts')
            local = logical_line(manifest['parts'][file - 1], local)
        else:
            require(file == 0, 'baseline row refers outside source')
        rows.append([address, local, column, isa, discriminator, op, fields[7:]])
    require(rows, 'missing line rows')
    return rows


def stable_sections(path):
    data = path.read_bytes()
    text = command('readelf', '-SW', str(path))
    result = {}
    presentation = {'.debug_info', '.debug_abbrev', '.debug_line', '.debug_str', '.debug_line_str'}
    for line in text.splitlines():
        match = re.match(r'\s*\[\s*\d+\]\s+(\S+)\s+PROGBITS\s+[0-9a-f]+\s+([0-9a-f]+)\s+([0-9a-f]+)', line)
        if match and (match[1].startswith('.debug_') or match[1] == '.eh_frame') and match[1] not in presentation:
            require(match[1] not in result, 'duplicate semantic section')
            start, size = int(match[2], 16), int(match[3], 16)
            require(start + size <= len(data), 'truncated section')
            result[match[1]] = digest(data[start:start + size])
    require('.debug_aranges' in result, 'missing address index')
    return result


def compare(left, right):
    require(left == right, 'single/multi-file semantic mismatch')


def negative_controls(info, lines, source, manifest, snapshot):
    # Mutate the independently decoded input, before normalization, to prove the
    # oracle cannot hide an erroneous coordinate, type edge or location value.
    variants = []
    for attr in ('DW_AT_type', 'DW_AT_location', 'DW_AT_decl_line', 'DW_AT_ranges'):
        match = re.search(r'(\b' + attr + r' \[DW_FORM_\w+\]\s+\()(0x[0-9a-f]+|[0-9]+)', info)
        if match:
            value = int(match[2], 16 if match[2].startswith('0x') else 10)
            replacement = str(value + 1)
            if attr == 'DW_AT_type':
                # Use another valid DIE offset, rather than only testing a
                # dangling reference. Canonical identity must remain distinct.
                offset = next(int(m[1], 16) for m in re.finditer(r'^0x([0-9a-f]+): +DW_TAG_', info, re.M)
                    if int(m[1], 16) != value)
                replacement = hex(offset)
            variants.append((info[:match.start(2)] + replacement + info[match.end(2):], lines))
    location = re.search(r'(DW_OP_(?:fbreg|breg\d+)\s+)(-?\d+)', info)
    if location:
        variants.append((info[:location.start(2)] + str(int(location[2]) + 1) + info[location.end(2):], lines))
    declaration = re.search(r'(DW_AT_decl_file \[DW_FORM_\w+\]\s+\(")([^"\n]+)', info)
    require(declaration is not None, 'fixture has no declaration-file controls')
    variants.append((info[:declaration.start(2)] + str(source) + info[declaration.end(2):], lines))
    row = re.search(r'^0x[0-9a-f]+\s+\d+\s+\d+\s+\d+\s+\d+\s+\d+\s+\d+[^\n]*', lines, re.M)
    require(row is not None, 'fixture has no line-row controls')
    for field in range(7):
        fields = row[0].split()
        fields[field] = hex(int(fields[field], 16) + 1) if field == 0 else str(int(fields[field]) + 1)
        variants.append((info, lines[:row.start()] + ' '.join(fields) + lines[row.end():]))
    variants.append((info, lines.replace('is_stmt end_sequence', 'is_stmt', 1)))
    for changed_info, changed_lines in variants:
        try:
            changed = {'dies': dies(changed_info, source, manifest),
                'rows': line_rows(changed_lines, source, manifest), 'sections': snapshot['sections']}
            compare(snapshot, changed)
        except ValueError:
            continue
        raise ValueError('semantic oracle accepted a negative control')
    return len(variants)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('original', type=Path)
    parser.add_argument('baseline', type=Path)
    parser.add_argument('partitioned', type=Path)
    parser.add_argument('result', type=Path)
    args = parser.parse_args()
    original, baseline, partitioned = [p.resolve(strict=True) for p in (args.original, args.baseline, args.partitioned)]
    args.result.mkdir(parents=True, exist_ok=False)
    sources = [Path(str(p) + '.c') for p in (baseline, partitioned)]
    manifest = bundle(sources[1], original, sources[0])
    snapshots = []
    for label, path, source, inventory in zip(('single', 'multi'), (baseline, partitioned), sources, (None, manifest)):
        info = command('llvm-dwarfdump', '--debug-info', '--show-form', str(path))
        lines = command('llvm-dwarfdump', '--debug-line', str(path))
        (args.result / (label + '-info.txt')).write_text(info)
        (args.result / (label + '-line.txt')).write_text(lines)
        snapshot = {'dies': dies(info, source, inventory), 'rows': line_rows(lines, source, inventory),
            'sections': stable_sections(path)}
        (args.result / (label + '-semantic.json')).write_text(json.dumps(snapshot, indent=4) + '\n')
        snapshots.append(snapshot)
    compare(*snapshots)
    controls = negative_controls(info, lines, sources[1], manifest, snapshots[1])
    result = {'status': 'MULTIFILE_SEMANTICS_PASS', 'diesIncludingNull': len(snapshots[0]['dies']),
        'lineRows': len(snapshots[0]['rows']), 'parts': len(manifest['parts']), 'negativeControls': controls,
        'stableSections': snapshots[0]['sections'],
        'llvmVersion': command('llvm-dwarfdump', '--version').strip(),
        'readelfVersion': command('readelf', '--version').splitlines()[0],
        'artifacts': {str(p): digest(p.read_bytes()) for p in (original, baseline, partitioned, *sources)}}
    (args.result / 'result.json').write_text(json.dumps(result, indent=4) + '\n')
    print(json.dumps(result, indent=4))


if __name__ == '__main__':
    main()
